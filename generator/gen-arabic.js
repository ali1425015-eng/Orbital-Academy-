function verbOfType(r, type) {
  if (type === 'sahih') { const v = r.pick(SAHIH); return { raf: v[0], jazm: v[1], nasb: v[2] }; }
  if (type === 'alif') { const v = r.pick(ALIF); return { raf: v[0], jazm: v[1], nasb: v[2] }; }
  if (type === 'waw') { const v = r.pick(WAW); return { raf: v[0], jazm: v[1], nasb: v[2] }; }
  if (type === 'ya') { const v = r.pick(YA); return { raf: v[0], jazm: v[1], nasb: v[2] }; }
  const f = fiveVerb(r); return { raf: f.raf, jazm: f.cut, nasb: f.cut };
}
