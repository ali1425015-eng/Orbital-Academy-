  const ctxs = r.shuffle(FIVE_CTX);
  const good = ctxs[0], goodS = good[1].replace('___', forms[good[0]]);
  const ds = ctxs.slice(1, 4).map(([cs, sent]) => { const wrongCs = r.pick(['raf', 'nasb', 'jarr'].filter(x => x !== cs)); return [sent.replace('___', forms[wrongCs]), 'في هذه الجملة الكلمة حكمها ' + CASE_AR[cs] + ' فتكون (' + forms[cs] + ') وليس (' + forms[wrongCs] + ').']; });
