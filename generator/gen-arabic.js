const SIGN_WORD = { 'مرفوع': 'رفعه', 'منصوب': 'نصبه', 'مجرور': 'جره' };

function endings(type) {
  return type === 'jam' ? { raf: 'ُونَ', nasb: 'ِينَ', jarr: 'ِينَ', other: ['َانِ', 'َيْنِ'] } : { raf: 'َانِ', nasb: 'َيْنِ', jarr: 'َيْنِ', other: ['ُونَ', 'ِينَ'] };
}
function soundForm(type) {
  return r => {
    const n = r.pick(NOUNS), [cs, role, sent] = r.pick(CTX), E = endings(type);
    const name = type === 'jam' ? 'جمع المذكر السالم' : 'المثنى';
    const signs = type === 'jam' ? 'يُرفع بالواو ويُنصب ويُجر بالياء' : 'يُرفع بالألف ويُنصب ويُجر بالياء';
    if (r.chance(0.55)) {
      const correct = n + E[cs];
      const wrongCase = cs === 'raf' ? n + E.nasb : n + E.raf;
      const m = mcq(r, correct, [[wrongCase, name + ' ' + signs + '، والكلمة هنا (' + role + ') حكمها ' + CASE_AR[cs] + '.'],
        [n + E.other[0], 'هذه صيغة ' + (type === 'jam' ? 'المثنى' : 'جمع المذكر السالم') + '، والمطلوب ' + name + '.'],
        [n + E.other[1], 'هذه صيغة ' + (type === 'jam' ? 'المثنى' : 'جمع المذكر السالم') + '، والمطلوب ' + name + '.']], x => x);
      return { d: role === 'اسم إنّ' || role === 'مضاف إليه' ? 2 : 1, q: 'اختر الصواب (' + name + '):\n' + sent, m, e: 'الكلمة ' + role + ' ' + ROLE_CASE[role] + '، و' + name + ' ' + signs + ' ← ' + correct + '.' };
    }
    const word = n + E[cs], full = sent.replace('___', word);
    const st = ROLE_CASE[role], sign = st === 'مرفوع' ? (type === 'jam' ? 'الواو' : 'الألف') : 'الياء';
    const why = ' لأنه ' + (type === 'jam' ? 'جمع مذكر سالم' : 'مثنى');
    const correct = role + ' ' + st + ' وعلامة ' + SIGN_WORD[st] + ' ' + sign + why;
    const roles = Object.keys(ROLE_CASE).filter(x => x !== role);
    const ds = [[role + ' ' + st + ' وعلامة ' + SIGN_WORD[st] + ' ' + (st === 'مرفوع' ? 'الضمة' : st === 'منصوب' ? 'الفتحة' : 'الكسرة'), name + ' لا يُعرب بالحركات الأصلية بل بالحروف.']];
    r.shuffle(roles).slice(0, 3).forEach(x => { const s2 = ROLE_CASE[x]; const sg = s2 === 'مرفوع' ? (type === 'jam' ? 'الواو' : 'الألف') : 'الياء'; ds.push([x + ' ' + s2 + ' وعلامة ' + SIGN_WORD[s2] + ' ' + sg + why, 'موقع الكلمة في الجملة ليس (' + x + ') بل (' + role + ').']); });
    const m = mcq(r, correct, ds, x => x);
    return { d: 2, q: 'ما إعراب كلمة (' + word + ') في جملة: «' + full + '»؟', m, e: correct + '.' };
  };
}
